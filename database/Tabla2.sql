CREATE TABLE IF NOT EXISTS `Vacunas` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Nombre` VARCHAR(255),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Dosis` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Numero` VARCHAR(255),
	`Vacunas_id` INTEGER,
	`Personas_id` INTEGER,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Carnet_salud` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Codigo` INTEGER,
	`Dosis_id` INTEGER,
	`Examenes_id` INTEGER,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Personas` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Primer_nombre` VARCHAR(255),
	`Segundo_nombre` VARCHAR(255),
	`Primer_apellido` VARCHAR(255),
	`Segundo_apellido` VARCHAR(255),
	`Cedula` INTEGER,
	`Edad` VARCHAR(255),
	`Correo` VARCHAR(255),
	`Fecha_nacimiento` DATE,
	`Examenes_id` INTEGER,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Examenes` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Nombre` VARCHAR(255),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Centros` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Nombre` VARCHAR(255),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Usuarios` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Nombre` VARCHAR(255),
	`Apellido` VARCHAR(255),
	`Cedula` INTEGER,
	`Centros_id` INTEGER,
	`Cargo` VARCHAR(255),
	PRIMARY KEY(`id`)
);


