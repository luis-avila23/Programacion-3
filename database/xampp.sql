CREATE TABLE IF NOT EXISTS `Vacunas` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Nombre` VARCHAR(255),
	`Centros_id` INTEGER,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Dosis` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Numero` VARCHAR(255),
	`Vacunas_id` INTEGER,
	`Personas_id` INTEGER,
	`Fecha_aplicacion` DATE,
	`Lote` VARCHAR(255),
	`Observacion` VARCHAR(255),
	`Estado` TEXT(65535),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Carnet` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Codigo` INTEGER,
	`Dosis_id` INTEGER,
	`Examenes_id` INTEGER,
	`Personas_id` INTEGER,
	`Fecha_emision` DATE,
	`Fecha_vencimiento` DATE,
	`Estatus` TEXT(65535),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Personas` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Primer_nombre` VARCHAR(255),
	`Segundo_nombre` VARCHAR(255),
	`Primer_apellido` VARCHAR(255),
	`Segundo_apellido` VARCHAR(255),
	`Cedula` INTEGER,
	`Edad` VARCHAR(255),
	`Correo` VARCHAR(255),
	`Fecha_nacimiento` DATE,
	`Examenes_id` INTEGER,
	`Tipo_sangre` VARCHAR(255),
	`Parroquias_id` INTEGER,
	`Subregiones_id` INTEGER,
	`Centros_id` INTEGER,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Examenes` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Nombre` VARCHAR(255),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Centros` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Nombre` VARCHAR(255),
	`id_Parroquias` INTEGER,
	`id_Subregiones` INTEGER,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Usuarios` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Nombre` VARCHAR(255),
	`Apellido` VARCHAR(255),
	`Cedula` INTEGER,
	`Centros_id` INTEGER,
	`Cargo` VARCHAR(255),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Estados` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`estado` VARCHAR(255),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Municipios` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Estados_id` INTEGER,
	`municipio` VARCHAR(255),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Parroquias` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`id_Municipios` INTEGER,
	`parroquia` VARCHAR(255),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Subregiones` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Nombre` VARCHAR(255),
	`Codigo_subregion` VARCHAR(255),
	`Estados_id` INTEGER,
	`Municipios_id` INTEGER,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Carnet_examenes` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Carnet_id` INTEGER,
	`Examenes_id` INTEGER,
	`Fecha_realizacion` DATE,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Auditoria` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Accion` VARCHAR(255),
	`Tabla_afectada` VARCHAR(255),
	`Registro_id` INTEGER,
	`Detalle` TEXT(65535),
	`Fecha` DATE,
	`Hora` DATETIME,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Registro` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
