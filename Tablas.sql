CREATE TABLE IF NOT EXISTS `Vacunas` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Name` VARCHAR(255),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Personas` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Name` VARCHAR(255),
	`C.I` VARCHAR(255),
	`Edad` VARCHAR(255),
	`Correo` VARCHAR(255),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Dosis` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Name` VARCHAR(255),
	`id_Vacunas` INTEGER NOT NULL,
	`id_Personas` INTEGER NOT NULL,
	PRIMARY KEY(`id`, `id_Vacunas`, `id_Personas`)
);


CREATE TABLE IF NOT EXISTS `Centro_Salud` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Código` INTEGER,
	`id_Dosis` INTEGER NOT NULL,
	`id_Examenes` INTEGER NOT NULL,
	PRIMARY KEY(`id`, `id_Dosis`, `id_Examenes`)
);


CREATE TABLE IF NOT EXISTS `Usuarios` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Name` VARCHAR(255),
	`id_Centros` INTEGER NOT NULL,
	PRIMARY KEY(`id`, `id_Centros`)
);


CREATE TABLE IF NOT EXISTS `Centros` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Name` VARCHAR(255),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Examenes` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Name` VARCHAR(255),
	PRIMARY KEY(`id`)
);


